"""
Module -- Candidate Chatbot

Called by the POST /chat endpoint in app/main.py. No Groq / OpenAI / external LLM.
Model: app/models/candidate_chatbot.joblib, trained by training/chatbot/train_chatbot.py.

* Only for candidates. Logged-in staff roles (HR, RECRUITER, HIRING_MANAGER,
  EMPLOYEE, INTERVIEWER, SUPER_ADMIN) get a "candidates only" message.
* Questions about recruiters, HR, hiring managers, super admins, interviewers
  or employees are not answered.
* Career questions are answered by the model trained on the original
  Career Guidance QA Dataset (training/chatbot/train_chatbot.py): a topic classifier plus a
  job-role detector; the answer is the dataset answer for that role and topic.
* Optional: if app/models/flan_t5_candidate/ exists (train_generative.py), answers
  are generated by the fine-tuned flan-t5-small, checked against the dataset answer.
* Job search (app/job_search.py) - by experience ("2-3 years", "fresher"), skill
  ("python"), city ("Hyderabad"), job type ("internship"), title, or any mix of these,
  plus full details of one job. Answers come only from the jobs the backend sends
  (job_context text/JSON or the structured `jobs` list). Runs before the career model.

"""

