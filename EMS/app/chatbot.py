# ============================================================
# MODEL LOADING
# ============================================================

_bundle = None
_generator = None
_generator_unavailable = False
_lock = threading.Lock()


def _get_model() -> dict:
    global _bundle
    if _bundle is None:
        with _lock:
            if _bundle is None:
                if not MODEL_PATH.exists():
                    raise RuntimeError(
                        f"Chatbot model not found at {MODEL_PATH}. Run 'python training/chatbot/train_chatbot.py' first.")
                _bundle = joblib.load(MODEL_PATH)
    return _bundle


def _get_generator():
    global _generator, _generator_unavailable
    if CHATBOT_MODE in ("dataset", "retrieval") or _generator_unavailable:
        return None
    if _generator is None:
        with _lock:
            if _generator is None and not _generator_unavailable:
                if not (GENERATIVE_MODEL_DIR / "config.json").exists():
                    _generator_unavailable = True
                    return None
                try:
                    import torch
                    from transformers import AutoModelForSeq2SeqLM, AutoTokenizer
                    device = "cuda" if torch.cuda.is_available() else "cpu"
                    tok = AutoTokenizer.from_pretrained(GENERATIVE_MODEL_DIR)
                    mdl = AutoModelForSeq2SeqLM.from_pretrained(GENERATIVE_MODEL_DIR).to(device).eval()
                    _generator = (tok, mdl, device)
                except Exception:
                    _generator_unavailable = True
                    return None
    return _generator


def load_chatbot_model() -> None:
    """Load the model now (called from app/main.py at server startup)."""
    _get_model()


def reload_models() -> None:
    """Call after retraining to load the new models without a restart."""
    global _bundle, _generator, _generator_unavailable
    with _lock:
        _bundle, _generator, _generator_unavailable = None, None, False


# ============================================================
# HELPERS
# ============================================================

def _normalize_role(role: Optional[str]) -> str:
    if not role:
        return "PUBLIC"
    return str(role).strip().upper()


def _last_user_message(history: Optional[list]) -> Optional[str]:
    for item in reversed(history or []):
        if isinstance(item, dict) and item.get("role") == "user" and item.get("content"):
            return str(item["content"])
    return None


def _jobs_answer(message: str, job_context=None, jobs=None, previous: Optional[str] = None) -> str:
    """Answer only from the job data sent by the backend. Nothing is invented."""
    return search_jobs(message, job_context=job_context, jobs=jobs,
                       previous_message=previous, no_jobs_message=NO_JOBS_MESSAGE)


def _previous_user_messages(history: Optional[list]) -> list:
    return [str(i["content"]) for i in reversed(history or [])
            if isinstance(i, dict) and i.get("role") == "user" and i.get("content")]


def _role_examples(model, n=6) -> str:
    preferred = ["Data Scientist", "Software Engineer", "Web Developer", "Data Analyst",
                 "UX/UI Designer", "QA Engineer", "Business Analyst", "Product Manager (Entry-level)"]
    picks = [r for r in preferred if r in model.roles][:n]
    return ", ".join(picks)


def _generate(question: str, role: str) -> Optional[str]:
    gen = _get_generator()
    if gen is None:
        return None
    import torch
    tok, mdl, device = gen
    prompt = f"Answer this career question. job role: {role} | question: {question.strip()}"
    enc = tok(prompt, max_length=96, truncation=True, return_tensors="pt").to(device)
    with torch.no_grad():
        out = mdl.generate(**enc, max_new_tokens=200, num_beams=3, no_repeat_ngram_size=4)
    text = tok.decode(out[0], skip_special_tokens=True).strip()
    return text if len(text) >= 20 else None


def _similar(a: str, b: str) -> float:
    return SequenceMatcher(None, normalize_text(a).split(), normalize_text(b).split()).ratio()


def _log_unknown(message: str, score: float) -> None:
    if not UNKNOWN_LOG_PATH:
        return
    try:
        with open(UNKNOWN_LOG_PATH, "a", encoding="utf-8") as f:
            f.write(json.dumps({"time": datetime.now().isoformat(timespec="seconds"),
                                "message": message, "best_score": round(score, 3)}) + "\n")
    except OSError:
        pass


